import { act, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { createCategory, deactivateCategory, listCategories, reactivateCategory, updateCategory } from '../services/categoryService.js'
import { CategoryManagementPage } from './CategoryManagementPage.jsx'

vi.mock('../services/categoryService.js', () => ({ listCategories: vi.fn(), createCategory: vi.fn(), updateCategory: vi.fn(), deactivateCategory: vi.fn(), reactivateCategory: vi.fn() }))
vi.mock('../../subcategories/components/SubcategoryManager.jsx', () => ({ SubcategoryManager: () => null }))

const categories = [
  { id: 2, nombre: 'Plomería', descripcion: 'Caños', icono: 'plomeria', activo: true },
  { id: 1, nombre: 'Anterior', descripcion: '', icono: 'cemento', activo: false },
]

describe('CategoryManagementPage', () => {
  beforeEach(() => vi.resetAllMocks())

  it('muestra carga, orden recibido, estados e íconos conocidos/desconocidos', async () => {
    listCategories.mockResolvedValue(categories)
    render(<CategoryManagementPage />)
    expect(screen.getByRole('status')).toHaveTextContent('Cargando categorías')
    expect(listCategories).toHaveBeenCalledWith({ signal: expect.any(AbortSignal) })
    expect(await screen.findByRole('heading', { name: 'Plomería' })).toBeInTheDocument()
    expect(screen.getByText('Caños')).toBeInTheDocument()
    expect(screen.getByText('ID 2 · Activa')).toBeInTheDocument()
    expect(screen.getByText('ID 1 · Inactiva')).toBeInTheDocument()
    expect(screen.getByText('Ícono desconocido: cemento')).toBeInTheDocument()
    expect(screen.queryByText('Ícono desconocido: plomeria')).not.toBeInTheDocument()
    expect(screen.getAllByRole('listitem').map((item) => item.querySelector('h2').textContent))
      .toEqual(['Plomería', 'Anterior'])
    expect(screen.getAllByRole('listitem')[0].querySelector('svg')).toBeInTheDocument()
    expect(screen.getAllByRole('listitem')[1].querySelector('svg')).toBeInTheDocument()
    expect(screen.getAllByRole('button', { name: /^Editar / }).map((button) => button.textContent)).toEqual(['Editar', 'Editar'])
  })

  it('muestra lista vacía', async () => {
    listCategories.mockResolvedValue([])
    render(<CategoryManagementPage />)
    expect(await screen.findByText('No hay categorías.')).toBeInTheDocument()
  })

  it('abre el alta solo al pulsar Crear categoría y permite cancelarla sin guardar', async () => {
    const user = userEvent.setup()
    listCategories.mockResolvedValue(categories)
    render(<CategoryManagementPage />)
    await screen.findByRole('heading', { name: 'Plomería' })
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.queryByRole('textbox', { name: 'Nombre' })).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Crear categoría' }))
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), 'Borrador')
    await user.click(screen.getByRole('button', { name: 'Cancelar' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(createCategory).not.toHaveBeenCalled()
    await user.click(screen.getByRole('button', { name: 'Crear categoría' }))
    expect(screen.getByRole('textbox', { name: 'Nombre' })).toHaveValue('')
  })

  it('muestra error y permite reintentar sin mostrar datos obsoletos', async () => {
    listCategories.mockRejectedValueOnce(new Error('Servidor no disponible')).mockResolvedValueOnce(categories)
    render(<CategoryManagementPage />)
    expect(await screen.findByRole('alert')).toHaveTextContent('Servidor no disponible')
    await userEvent.setup().click(screen.getByRole('button', { name: 'Reintentar' }))
    expect(await screen.findByRole('heading', { name: 'Plomería' })).toBeInTheDocument()
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
    expect(listCategories).toHaveBeenCalledTimes(2)
  })

  it('aborta e ignora una respuesta tardía al desmontar', async () => {
    let finish
    listCategories.mockImplementation(() => new Promise((resolve) => { finish = resolve }))
    const { unmount } = render(<CategoryManagementPage />)
    const signal = listCategories.mock.calls[0][0].signal
    unmount()
    expect(signal.aborted).toBe(true)
    await act(async () => finish(categories))
    expect(screen.queryByText('Plomería')).not.toBeInTheDocument()
  })

  it('crea con clave GLG, nombre recortado y descripción vacía; recarga en orden del servidor', async () => {
    const user = userEvent.setup()
    listCategories.mockResolvedValueOnce(categories).mockResolvedValueOnce([categories[1], categories[0]])
    createCategory.mockResolvedValue({ id: 3 })
    render(<CategoryManagementPage />)
    await screen.findByRole('heading', { name: 'Plomería' })
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Crear categoría' }))
    expect(screen.getByRole('dialog', { name: 'Nueva categoría' })).toBeInTheDocument()
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), '  Pintura  ')
    await user.click(screen.getByRole('radio', { name: 'Pintura' }))
    await user.click(screen.getByRole('button', { name: 'Guardar categoría' }))
    expect(createCategory).toHaveBeenCalledWith({ nombre: 'Pintura', descripcion: '', icono: 'pintura' })
    await waitFor(() => expect(listCategories).toHaveBeenCalledTimes(2))
    expect(screen.getAllByRole('listitem').map((item) => item.querySelector('h2').textContent)).toEqual(['Anterior', 'Plomería'])
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  })

  it('edita una clave desconocida sin cambiarla y permite reemplazarla', async () => {
    const user = userEvent.setup()
    listCategories.mockResolvedValue(categories)
    updateCategory.mockResolvedValue({})
    render(<CategoryManagementPage />)
    await screen.findByRole('heading', { name: 'Anterior' })
    await user.click(screen.getByRole('button', { name: 'Editar Anterior' }))
    expect(screen.getByRole('dialog', { name: 'Editar Anterior' })).toBeInTheDocument()
    expect(screen.getByRole('radio', { name: 'Conservar ícono actual (cemento)' })).toBeChecked()
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    expect(updateCategory).toHaveBeenCalledWith(1, { nombre: 'Anterior', descripcion: '', icono: 'cemento' })
    await waitFor(() => expect(screen.getByRole('button', { name: 'Editar Anterior' })).toBeEnabled())
    await user.click(screen.getByRole('button', { name: 'Editar Anterior' }))
    await user.click(screen.getByRole('radio', { name: 'Materiales' }))
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    expect(updateCategory).toHaveBeenLastCalledWith(1, { nombre: 'Anterior', descripcion: '', icono: 'materiales' })
    expect(await screen.findByText('Categoría actualizada.')).toBeInTheDocument()
    await waitFor(() => expect(screen.queryByText('Categoría actualizada.')).not.toBeInTheDocument(), { timeout: 5000 })
  })

  it('conserva valores y errores de campo tras validación; cancelar vuelve al alta', async () => {
    const user = userEvent.setup()
    listCategories.mockResolvedValue(categories)
    createCategory.mockRejectedValue({ status: 409, message: 'Nombre duplicado', fieldErrors: [{ field: 'nombre', message: 'Ya existe' }] })
    render(<CategoryManagementPage />)
    await screen.findByRole('heading', { name: 'Plomería' })
    await user.click(screen.getByRole('button', { name: 'Crear categoría' }))
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), 'Repetida')
    await user.click(screen.getByRole('radio', { name: 'Agua' }))
    await user.click(screen.getByRole('button', { name: 'Guardar categoría' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Nombre duplicado')
    expect(screen.getByText('Ya existe')).toBeInTheDocument()
    expect(screen.getByRole('textbox', { name: /Nombre/ })).toHaveValue('Repetida')
    expect(screen.getByRole('radio', { name: 'Agua' })).toBeChecked()
    await user.click(screen.getByRole('button', { name: 'Cancelar' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Editar Plomería' }))
    expect(screen.getByRole('dialog', { name: 'Editar Plomería' })).toBeInTheDocument()
    expect(screen.getByRole('textbox', { name: 'Nombre' })).toHaveValue('Plomería')
    await user.click(screen.getByRole('button', { name: 'Cancelar edición' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.queryByRole('textbox', { name: 'Nombre' })).not.toBeInTheDocument()
  })

  it('conserva el formulario de edición en el modal tras un conflicto y lo reinicia al cancelar', async () => {
    const user = userEvent.setup()
    listCategories.mockResolvedValue(categories)
    updateCategory.mockRejectedValue({ status: 409, message: 'Nombre duplicado' })
    render(<CategoryManagementPage />)
    await screen.findByRole('heading', { name: 'Plomería' })
    await user.click(screen.getByRole('button', { name: 'Editar Plomería' }))
    const dialog = screen.getByRole('dialog', { name: 'Editar Plomería' })
    expect(dialog).toContainElement(screen.getByRole('button', { name: 'Guardar cambios' }))
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), ' nueva')
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    expect(await within(dialog).findByRole('alert')).toHaveTextContent('Nombre duplicado')
    expect(screen.getByRole('textbox', { name: 'Nombre' })).toHaveValue('Plomería nueva')
    await user.click(screen.getByRole('button', { name: 'Cancelar edición' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Editar Plomería' }))
    expect(screen.getByRole('textbox', { name: 'Nombre' })).toHaveValue('Plomería')
  })

  it.each([0, 503])('bloquea otra mutación tras error incierto %i hasta consultar la lista', async (status) => {
    const user = userEvent.setup()
    listCategories.mockResolvedValue(categories)
    createCategory.mockRejectedValueOnce({ status, message: 'Resultado incierto' }).mockResolvedValueOnce({})
    render(<CategoryManagementPage />)
    await screen.findByRole('heading', { name: 'Plomería' })
    await user.click(screen.getByRole('button', { name: 'Crear categoría' }))
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), 'Nueva')
    await user.click(screen.getByRole('radio', { name: 'Gas' }))
    await user.click(screen.getByRole('button', { name: 'Guardar categoría' }))
    expect(await screen.findByRole('button', { name: 'Consultar estado actual' })).toBeEnabled()
    expect(screen.getByRole('button', { name: 'Guardar categoría' })).toBeDisabled()
    expect(createCategory).toHaveBeenCalledTimes(1)
    await user.click(screen.getByRole('button', { name: 'Consultar estado actual' }))
    expect(await screen.findByRole('button', { name: 'Guardar categoría' })).toBeEnabled()
    expect(screen.getByRole('textbox', { name: 'Nombre' })).toHaveValue('Nueva')
    await user.click(screen.getByRole('button', { name: 'Guardar categoría' }))
    expect(createCategory).toHaveBeenCalledTimes(2)
  })

  it('impide doble envío mientras la mutación está pendiente', async () => {
    const user = userEvent.setup()
    let finish
    listCategories.mockResolvedValue(categories)
    createCategory.mockImplementation(() => new Promise((resolve) => { finish = resolve }))
    render(<CategoryManagementPage />)
    await screen.findByRole('heading', { name: 'Plomería' })
    await user.click(screen.getByRole('button', { name: 'Crear categoría' }))
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), 'Nueva')
    await user.click(screen.getByRole('radio', { name: 'Gas' }))
    await user.click(screen.getByRole('button', { name: 'Guardar categoría' }))
    expect(screen.getByRole('button', { name: 'Guardar categoría' })).toBeDisabled()
    expect(createCategory).toHaveBeenCalledTimes(1)
    await act(async () => finish({}))
  })

  it('aplica límites HTML y permite seleccionar el ícono con teclado', async () => {
    const user = userEvent.setup()
    listCategories.mockResolvedValue([])
    render(<CategoryManagementPage />)
    await screen.findByText('No hay categorías.')
    await user.click(screen.getByRole('button', { name: 'Crear categoría' }))
    const name = screen.getByRole('textbox', { name: 'Nombre' })
    const description = screen.getByRole('textbox', { name: 'Descripción' })
    expect(name).toBeRequired()
    expect(name).toHaveAttribute('maxlength', '160')
    expect(description).toHaveAttribute('maxlength', '1000')
    expect(screen.getByRole('group', { name: 'Instalaciones' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Guardar categoría' }))
    expect(createCategory).not.toHaveBeenCalled()
    screen.getByRole('radio', { name: 'Materiales' }).focus()
    await user.keyboard(' ')
    expect(screen.getByRole('radio', { name: 'Materiales' })).toBeChecked()
  })

  it('mantiene el bloqueo si falla la consulta posterior a una respuesta incierta', async () => {
    const user = userEvent.setup()
    listCategories.mockResolvedValueOnce(categories).mockRejectedValueOnce(new Error('Sin conexión')).mockResolvedValueOnce(categories)
    createCategory.mockRejectedValue({ status: 0, message: 'Resultado incierto' })
    render(<CategoryManagementPage />)
    await screen.findByRole('heading', { name: 'Plomería' })
    await user.click(screen.getByRole('button', { name: 'Crear categoría' }))
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), 'Nueva')
    await user.click(screen.getByRole('radio', { name: 'Gas' }))
    await user.click(screen.getByRole('button', { name: 'Guardar categoría' }))
    await user.click(await screen.findByRole('button', { name: 'Consultar estado actual' }))
    expect(await within(screen.getByRole('dialog')).findByText('Sin conexión')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Guardar categoría' })).toBeDisabled()
    expect(createCategory).toHaveBeenCalledTimes(1)
    await user.click(screen.getByRole('button', { name: 'Consultar estado actual' }))
    await waitFor(() => expect(screen.getByRole('button', { name: 'Guardar categoría' })).toBeEnabled())
  })

  it('cancelar la confirmación no cambia el estado; confirmar desactiva y reactiva con recarga', async () => {
    const user = userEvent.setup()
    listCategories.mockResolvedValueOnce(categories)
      .mockResolvedValueOnce([{ ...categories[0], activo: false }, categories[1]])
      .mockResolvedValueOnce(categories)
    deactivateCategory.mockResolvedValue({ ...categories[0], activo: false })
    reactivateCategory.mockResolvedValue(categories[0])
    render(<CategoryManagementPage />)
    await screen.findByRole('heading', { name: 'Plomería' })
    await user.click(screen.getByRole('button', { name: 'Desactivar Plomería' }))
    expect(screen.getByRole('dialog', { name: 'Desactivar Plomería' })).toHaveTextContent('Plomería')
    await user.click(screen.getByRole('button', { name: 'Cancelar' }))
    expect(deactivateCategory).not.toHaveBeenCalled()
    await user.click(screen.getByRole('button', { name: 'Desactivar Plomería' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar desactivación' }))
    expect(deactivateCategory).toHaveBeenCalledExactlyOnceWith(2)
    expect(await screen.findByRole('button', { name: 'Reactivar Plomería' })).toBeInTheDocument()
    expect(screen.getByText('ID 2 · Inactiva')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Reactivar Plomería' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar reactivación' }))
    expect(reactivateCategory).toHaveBeenCalledExactlyOnceWith(2)
    expect(await screen.findByText('ID 2 · Activa')).toBeInTheDocument()
    expect(listCategories).toHaveBeenCalledTimes(3)
  })

  it.each([0, 503])('bloquea cambios tras resultado incierto de estado %i hasta revisar', async (status) => {
    const user = userEvent.setup()
    listCategories.mockResolvedValue(categories)
    deactivateCategory.mockRejectedValue({ status, message: 'Resultado incierto' })
    render(<CategoryManagementPage />)
    await screen.findByRole('heading', { name: 'Plomería' })
    await user.click(screen.getByRole('button', { name: 'Desactivar Plomería' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar desactivación' }))
    expect(await screen.findByRole('button', { name: 'Consultar estado actual' })).toBeEnabled()
    expect(screen.getByRole('button', { name: 'Desactivar Plomería' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Crear categoría' })).toBeDisabled()
    expect(deactivateCategory).toHaveBeenCalledTimes(1)
    await user.click(screen.getByRole('button', { name: 'Consultar estado actual' }))
    await waitFor(() => expect(screen.getByRole('button', { name: 'Desactivar Plomería' })).toBeEnabled())
    expect(deactivateCategory).toHaveBeenCalledTimes(1)
  })

  it('mantiene el bloqueo cuando falla la revisión posterior a una desactivación incierta', async () => {
    const user = userEvent.setup()
    listCategories.mockResolvedValueOnce(categories).mockRejectedValueOnce(new Error('Sin conexión')).mockResolvedValueOnce(categories)
    deactivateCategory.mockRejectedValue({ status: 503, message: 'Resultado incierto' })
    render(<CategoryManagementPage />)
    await screen.findByRole('heading', { name: 'Plomería' })
    await user.click(screen.getByRole('button', { name: 'Desactivar Plomería' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar desactivación' }))
    await user.click(await screen.findByRole('button', { name: 'Consultar estado actual' }))
    expect(await screen.findByText('Sin conexión')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Crear categoría' })).toBeDisabled()
    expect(deactivateCategory).toHaveBeenCalledTimes(1)
    await user.click(screen.getByRole('button', { name: 'Consultar estado actual' }))
    await waitFor(() => expect(screen.getByRole('button', { name: 'Desactivar Plomería' })).toBeEnabled())
  })

  it.each([404, 409])('un %i cierto muestra error y permite consultar el listado', async (status) => {
    const user = userEvent.setup()
    listCategories.mockResolvedValue(categories)
    deactivateCategory.mockRejectedValue({ status, message: 'Estado cambiado por otro usuario' })
    render(<CategoryManagementPage />)
    await screen.findByRole('heading', { name: 'Plomería' })
    await user.click(screen.getByRole('button', { name: 'Desactivar Plomería' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar desactivación' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Estado cambiado por otro usuario')
    await user.click(screen.getByRole('button', { name: 'Consultar estado actual' }))
    await waitFor(() => expect(listCategories).toHaveBeenCalledTimes(2))
  })

  it('deshabilita acciones duplicadas mientras espera el cambio de estado', async () => {
    const user = userEvent.setup()
    let finish
    listCategories.mockResolvedValue(categories)
    deactivateCategory.mockImplementation(() => new Promise((resolve) => { finish = resolve }))
    render(<CategoryManagementPage />)
    await screen.findByRole('heading', { name: 'Plomería' })
    await user.click(screen.getByRole('button', { name: 'Desactivar Plomería' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar desactivación' }))
    expect(screen.getByRole('button', { name: 'Crear categoría' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Desactivar Plomería' })).toBeDisabled()
    expect(deactivateCategory).toHaveBeenCalledTimes(1)
    await act(async () => finish({ ...categories[0], activo: false }))
  })

  it('conserva la confirmación si falla la recarga tras una desactivación exitosa', async () => {
    const user = userEvent.setup()
    listCategories.mockResolvedValueOnce(categories).mockRejectedValueOnce(new Error('Lectura fallida')).mockResolvedValueOnce([{ ...categories[0], activo: false }, categories[1]])
    deactivateCategory.mockResolvedValue({ ...categories[0], activo: false })
    render(<CategoryManagementPage />)
    await screen.findByRole('heading', { name: 'Plomería' })
    await user.click(screen.getByRole('button', { name: 'Desactivar Plomería' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar desactivación' }))
    expect(await screen.findByText(/La lista no pudo actualizarse/)).toHaveTextContent('Categoría desactivada.')
    expect(deactivateCategory).toHaveBeenCalledTimes(1)
    await user.click(screen.getByRole('button', { name: 'Reintentar' }))
    expect(await screen.findByRole('button', { name: 'Reactivar Plomería' })).toBeInTheDocument()
    expect(deactivateCategory).toHaveBeenCalledTimes(1)
  })

  it('recorre alta, edición, desactivación y reactivación según las listas del servidor', async () => {
    const user = userEvent.setup()
    const created = { id: 3, nombre: 'Pintura', descripcion: '', icono: 'pintura', activo: true }
    const edited = { ...created, nombre: 'Pinturas' }
    listCategories.mockResolvedValueOnce([]).mockResolvedValueOnce([created])
      .mockResolvedValueOnce([edited]).mockResolvedValueOnce([{ ...edited, activo: false }]).mockResolvedValueOnce([edited])
    createCategory.mockResolvedValue(created)
    updateCategory.mockResolvedValue(edited)
    deactivateCategory.mockResolvedValue({ ...edited, activo: false })
    reactivateCategory.mockResolvedValue(edited)
    render(<CategoryManagementPage />)
    await screen.findByText('No hay categorías.')
    await user.click(screen.getByRole('button', { name: 'Crear categoría' }))
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), 'Pintura')
    await user.click(screen.getByRole('radio', { name: 'Pintura' }))
    await user.click(screen.getByRole('button', { name: 'Guardar categoría' }))
    await screen.findByRole('button', { name: 'Editar Pintura' })
    await user.click(screen.getByRole('button', { name: 'Editar Pintura' }))
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), 's')
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    await screen.findByRole('button', { name: 'Desactivar Pinturas' })
    await user.click(screen.getByRole('button', { name: 'Desactivar Pinturas' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar desactivación' }))
    await screen.findByRole('button', { name: 'Reactivar Pinturas' })
    await user.click(screen.getByRole('button', { name: 'Reactivar Pinturas' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar reactivación' }))
    expect(await screen.findByText('ID 3 · Activa')).toBeInTheDocument()
    expect(listCategories).toHaveBeenCalledTimes(5)
    expect(createCategory).toHaveBeenCalledTimes(1)
    expect(updateCategory).toHaveBeenCalledWith(3, expect.objectContaining({ nombre: 'Pinturas' }))
    expect(deactivateCategory).toHaveBeenCalledWith(3)
    expect(reactivateCategory).toHaveBeenCalledWith(3)
  })
})
