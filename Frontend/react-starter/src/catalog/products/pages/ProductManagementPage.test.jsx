import { act, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { MemoryRouter, Route, Routes, useLocation } from 'react-router-dom'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { listCategories } from '../../categories/services/categoryService.js'
import { listCharacteristics } from '../services/characteristicService.js'
import { createProduct, deactivateProduct, getProduct, listProducts, reactivateProduct, updateProduct } from '../services/productService.js'
import { ProductManagementPage } from './ProductManagementPage.jsx'

vi.mock('../services/productService.js', () => ({ listProducts: vi.fn(), getProduct: vi.fn(), createProduct: vi.fn(), updateProduct: vi.fn(), deactivateProduct: vi.fn(), reactivateProduct: vi.fn() }))
vi.mock('../../categories/services/categoryService.js', () => ({ listCategories: vi.fn() }))
vi.mock('../services/characteristicService.js', () => ({ listCharacteristics: vi.fn() }))

const active = { id: 1, nombre: 'Arena', categoriaId: 3, descripcion: 'Fina', precioReferencia: 250, disponible: true, activo: true, destacado: false }
const inactive = { id: 2, nombre: 'Cemento', categoriaId: 4, descripcion: '', precioReferencia: 500, disponible: false, activo: false, destacado: true }
const makePage = (page, content = [], totalPages = 2) => ({ content, page, size: 20, totalElements: 21, totalPages })

function Location() {
  const location = useLocation()
  return <output data-testid="location">{location.pathname}{location.search}</output>
}

function renderPage(path = '/app/catalog/products') {
  return render(<MemoryRouter initialEntries={[path]}><Location /><Routes><Route path="/app/catalog/products" element={<ProductManagementPage />} /></Routes></MemoryRouter>)
}

describe('ProductManagementPage', () => {
  beforeEach(() => {
    vi.resetAllMocks()
    listCategories.mockResolvedValue([{ id: 3, nombre: 'Áridos', activo: true }, { id: 4, nombre: 'Vieja', activo: false }])
    listCharacteristics.mockResolvedValue([{ id: 7, nombre: 'Color' }, { id: 8, nombre: 'Peso' }])
  })

  it('carga productos activos e inactivos, permite recorrer páginas y conserva el filtro', async () => {
    listProducts.mockResolvedValue(makePage(0, [active, inactive]))
      .mockResolvedValueOnce(makePage(0, [active, inactive])).mockResolvedValueOnce(makePage(1, []))
    renderPage('/app/catalog/products?nombre=arena&page=0')
    expect(screen.getByText('Cargando productos…')).toBeInTheDocument()
    expect(await screen.findByRole('heading', { name: 'Arena' })).toBeInTheDocument()
    expect(screen.getByText(/ID 1 · Categoría 3 · Activo · Disponible/)).toBeInTheDocument()
    expect(screen.getByText(/ID 2 · Categoría 4 · Inactivo · No disponible/)).toBeInTheDocument()
    expect(screen.getByText(/Precio de referencia: 500 · Destacado/)).toBeInTheDocument()
    expect(listProducts).toHaveBeenCalledWith(0, 'arena', { signal: expect.any(AbortSignal) })
    await userEvent.setup().click(screen.getByRole('button', { name: 'Siguiente' }))
    expect(await screen.findByText('No hay productos en esta página.')).toBeInTheDocument()
    expect(screen.getByTestId('location')).toHaveTextContent('nombre=arena&page=1')
    expect(listProducts).toHaveBeenLastCalledWith(1, 'arena', { signal: expect.any(AbortSignal) })
    expect(screen.getByRole('button', { name: 'Siguiente' })).toBeDisabled()
    await userEvent.setup().click(screen.getByRole('button', { name: 'Anterior' }))
    expect(screen.getByTestId('location')).toHaveTextContent('nombre=arena&page=0')
  })

  it('busca al enviar, recorta el nombre, reinicia página y limpia el filtro', async () => {
    listProducts.mockResolvedValue(makePage(2, [active], 4))
    const user = userEvent.setup()
    renderPage('/app/catalog/products?page=2')
    await screen.findByRole('heading', { name: 'Arena' })
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), '  Cemento  ')
    expect(listProducts).toHaveBeenCalledTimes(1)
    await user.click(screen.getByRole('button', { name: 'Buscar' }))
    expect(screen.getByTestId('location')).toHaveTextContent('nombre=Cemento&page=0')
    await waitFor(() => expect(listProducts).toHaveBeenLastCalledWith(0, 'Cemento', { signal: expect.any(AbortSignal) }))
    await user.click(screen.getByRole('button', { name: 'Limpiar búsqueda' }))
    expect(screen.getByTestId('location')).toHaveTextContent('/app/catalog/products?page=0')
    await waitFor(() => expect(listProducts).toHaveBeenLastCalledWith(0, undefined, { signal: expect.any(AbortSignal) }))
  })

  it('rechaza una búsqueda vacía sin alterar la URL ni repetir la consulta', async () => {
    listProducts.mockResolvedValue(makePage(0, [active]))
    renderPage()
    await screen.findByRole('heading', { name: 'Arena' })
    const user = userEvent.setup()
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), '   ')
    await user.click(screen.getByRole('button', { name: 'Buscar' }))
    expect(screen.getByRole('alert')).toHaveTextContent('Ingresá un nombre')
    expect(screen.getByTestId('location')).toHaveTextContent('/app/catalog/products')
    expect(screen.getByRole('heading', { name: 'Arena' })).toBeInTheDocument()
    expect(listProducts).toHaveBeenCalledTimes(1)
  })

  it('no consulta un enlace directo con nombre vacío y permite limpiarlo', async () => {
    listProducts.mockResolvedValue(makePage(0, []))
    renderPage('/app/catalog/products?nombre=%20%20&page=0')
    expect(screen.getByRole('alert')).toHaveTextContent('Ingresá un nombre')
    expect(listProducts).not.toHaveBeenCalled()
    await userEvent.setup().click(screen.getByRole('button', { name: 'Limpiar búsqueda' }))
    await waitFor(() => expect(listProducts).toHaveBeenCalledWith(0, undefined, { signal: expect.any(AbortSignal) }))
  })

  it('muestra error y reintenta; descarta respuestas anteriores', async () => {
    let finishOld
    listProducts.mockImplementationOnce(() => new Promise((resolve) => { finishOld = resolve }))
      .mockRejectedValueOnce(new Error('Servidor no disponible'))
      .mockResolvedValueOnce(makePage(0, [inactive]))
    const user = userEvent.setup()
    renderPage()
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), 'Cemento')
    await user.click(screen.getByRole('button', { name: 'Buscar' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Servidor no disponible')
    await user.click(screen.getByRole('button', { name: 'Reintentar' }))
    expect(await screen.findByRole('heading', { name: 'Cemento' })).toBeInTheDocument()
    await act(async () => finishOld(makePage(0, [active])))
    expect(screen.queryByRole('heading', { name: 'Arena' })).not.toBeInTheDocument()
  })

  it('crea sin características y recarga la lista', async () => {
    listProducts.mockResolvedValue(makePage(0, [active]))
    createProduct.mockResolvedValue({ id: 3 })
    const user = userEvent.setup()
    renderPage()
    await screen.findByRole('heading', { name: 'Arena' })
    await user.click(screen.getByRole('button', { name: 'Crear producto' }))
    const form = within(await screen.findByRole('dialog'))
    expect(screen.queryByRole('option', { name: 'Vieja' })).not.toBeInTheDocument()
    await user.type(form.getByRole('textbox', { name: 'Nombre' }), 'Cal')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Categoría' }), '3')
    await user.type(screen.getByRole('textbox', { name: 'Precio de referencia' }), '12.50')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Disponibilidad' }), 'true')
    await user.click(screen.getByRole('button', { name: 'Guardar producto' }))
    await waitFor(() => expect(createProduct).toHaveBeenCalledWith({ nombre: 'Cal', categoriaId: 3, descripcion: '', precioReferencia: '12.50', disponible: true, caracteristicas: [] }))
    await waitFor(() => expect(listProducts).toHaveBeenCalledTimes(2))
  })

  it('crea con varias características sin repetir IDs', async () => {
    listProducts.mockResolvedValue(makePage(0, [active]))
    createProduct.mockResolvedValue({})
    const user = userEvent.setup()
    renderPage()
    await screen.findByRole('heading', { name: 'Arena' })
    await user.click(screen.getByRole('button', { name: 'Crear producto' }))
    const form = within(await screen.findByRole('dialog'))
    await user.type(form.getByRole('textbox', { name: 'Nombre' }), 'Cal')
    await user.selectOptions(form.getByRole('combobox', { name: 'Categoría' }), '3')
    await user.type(form.getByRole('textbox', { name: 'Precio de referencia' }), '12')
    await user.selectOptions(form.getByRole('combobox', { name: 'Disponibilidad' }), 'true')
    await user.click(form.getByRole('button', { name: 'Agregar característica' }))
    await user.selectOptions(form.getByRole('combobox', { name: 'Característica' }), '7')
    await user.type(form.getByRole('textbox', { name: 'Valor' }), 'Rojo')
    await user.click(form.getByRole('button', { name: 'Agregar característica' }))
    await user.selectOptions(form.getAllByRole('combobox', { name: 'Característica' })[1], '8')
    await user.type(form.getAllByRole('textbox', { name: 'Valor' })[1], '25')
    await user.type(form.getAllByRole('textbox', { name: 'Unidad' })[1], 'kg')
    await user.click(form.getByRole('button', { name: 'Guardar producto' }))
    await waitFor(() => expect(createProduct).toHaveBeenCalledWith(expect.objectContaining({ caracteristicas: [
      { caracteristicaId: 7, valor: 'Rojo', unidad: '' }, { caracteristicaId: 8, valor: '25', unidad: 'kg' },
    ] })))
  })

  it('edita conservando categoría inactiva y envía la lista completa al quitar y agregar características', async () => {
    listProducts.mockResolvedValue(makePage(0, [inactive]))
    getProduct.mockResolvedValue({ ...inactive, caracteristicas: [{ caracteristicaId: 7, nombre: 'Color', valor: 'Gris', unidad: '' }] })
    updateProduct.mockResolvedValue({})
    const user = userEvent.setup()
    renderPage()
    await screen.findByRole('heading', { name: 'Cemento' })
    await user.click(screen.getByRole('button', { name: 'Editar Cemento' }))
    expect(await screen.findByRole('heading', { name: 'Editar Cemento' })).toBeInTheDocument()
    expect(getProduct).toHaveBeenCalledWith(2, { signal: expect.any(AbortSignal) })
    expect(screen.getByRole('option', { name: 'Vieja (inactiva actual)' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Quitar característica' }))
    await user.click(screen.getByRole('button', { name: 'Agregar característica' }))
    await user.selectOptions(screen.getByRole('combobox', { name: 'Característica' }), '8')
    await user.type(screen.getByRole('textbox', { name: 'Valor' }), '25')
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    await waitFor(() => expect(updateProduct).toHaveBeenCalledWith(2, expect.objectContaining({ categoriaId: 4, caracteristicas: [{ caracteristicaId: 8, valor: '25', unidad: '' }] })))
    expect(updateProduct.mock.calls[0][1]).not.toHaveProperty('activo')
    expect(updateProduct.mock.calls[0][1]).not.toHaveProperty('destacado')
  })

  it('conserva el formulario ante 400 y evita escritura al cancelar', async () => {
    listProducts.mockResolvedValue(makePage(0, [active]))
    createProduct.mockRejectedValue({ status: 400, message: 'Dato inválido', fieldErrors: [{ field: 'nombre', message: 'Nombre repetido' }] })
    const user = userEvent.setup()
    renderPage()
    await screen.findByRole('heading', { name: 'Arena' })
    await user.click(screen.getByRole('button', { name: 'Crear producto' }))
    const form = within(await screen.findByRole('dialog'))
    await user.type(form.getByRole('textbox', { name: 'Nombre' }), 'Cal')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Categoría' }), '3')
    await user.type(screen.getByRole('textbox', { name: 'Precio de referencia' }), '12')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Disponibilidad' }), 'true')
    await user.click(screen.getByRole('button', { name: 'Guardar producto' }))
    expect(await screen.findByText('Nombre repetido')).toBeInTheDocument()
    expect(form.getByRole('textbox', { name: 'Nombre' })).toHaveValue('Cal')
    await user.click(screen.getByRole('button', { name: 'Cancelar' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(createProduct).toHaveBeenCalledTimes(1)
  })

  it('mantiene el modal ante 404 del detalle y permite cerrarlo sin mutar', async () => {
    listProducts.mockResolvedValue(makePage(0, [active]))
    getProduct.mockRejectedValue({ status: 404, message: 'Producto no encontrado' })
    const user = userEvent.setup()
    renderPage()
    await screen.findByRole('heading', { name: 'Arena' })
    await user.click(screen.getByRole('button', { name: 'Editar Arena' }))
    expect(await screen.findByText('Producto no encontrado')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Cerrar' }))
    expect(updateProduct).not.toHaveBeenCalled()
  })

  it('conserva valores ante 404 de categoría o característica al guardar', async () => {
    listProducts.mockResolvedValue(makePage(0, [active]))
    createProduct.mockRejectedValue({ status: 404, message: 'Categoría o característica no encontrada' })
    const user = userEvent.setup()
    renderPage()
    await screen.findByRole('heading', { name: 'Arena' })
    await user.click(screen.getByRole('button', { name: 'Crear producto' }))
    const form = within(await screen.findByRole('dialog'))
    await user.type(form.getByRole('textbox', { name: 'Nombre' }), 'Cal')
    await user.selectOptions(form.getByRole('combobox', { name: 'Categoría' }), '3')
    await user.type(form.getByRole('textbox', { name: 'Precio de referencia' }), '12')
    await user.selectOptions(form.getByRole('combobox', { name: 'Disponibilidad' }), 'true')
    await user.click(form.getByRole('button', { name: 'Guardar producto' }))
    expect(await screen.findByText('Categoría o característica no encontrada')).toBeInTheDocument()
    expect(form.getByRole('textbox', { name: 'Nombre' })).toHaveValue('Cal')
    expect(form.getByRole('button', { name: 'Guardar producto' })).toBeEnabled()
  })

  it('bloquea doble envío y cancelación mientras guarda; exige consulta tras fallo incierto', async () => {
    listProducts.mockResolvedValue(makePage(0, [active]))
    let rejectMutation
    createProduct.mockImplementation(() => new Promise((_, reject) => { rejectMutation = reject }))
    const user = userEvent.setup()
    renderPage()
    await screen.findByRole('heading', { name: 'Arena' })
    await user.click(screen.getByRole('button', { name: 'Crear producto' }))
    const form = within(await screen.findByRole('dialog'))
    await user.type(form.getByRole('textbox', { name: 'Nombre' }), 'Cal')
    await user.selectOptions(form.getByRole('combobox', { name: 'Categoría' }), '3')
    await user.type(form.getByRole('textbox', { name: 'Precio de referencia' }), '12')
    await user.selectOptions(form.getByRole('combobox', { name: 'Disponibilidad' }), 'true')
    await user.click(form.getByRole('button', { name: 'Guardar producto' }))
    expect(form.getByRole('button', { name: 'Guardar producto' })).toBeDisabled()
    expect(form.getByRole('button', { name: 'Cancelar' })).toBeDisabled()
    expect(createProduct).toHaveBeenCalledTimes(1)
    await act(async () => rejectMutation({ status: 503, message: 'Sin respuesta' }))
    expect(await screen.findByText('Sin respuesta')).toBeInTheDocument()
    expect(form.getByRole('button', { name: 'Guardar producto' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: 'Consultar estado actual' }))
    await waitFor(() => expect(listProducts).toHaveBeenCalledTimes(2))
    await waitFor(() => expect(form.getByRole('button', { name: 'Guardar producto' })).toBeEnabled())
    expect(createProduct).toHaveBeenCalledTimes(1)
  })

  it('vuelve a la última página disponible cuando la recarga queda fuera del total', async () => {
    listProducts.mockResolvedValueOnce(makePage(2, [active], 3))
      .mockResolvedValueOnce({ content: [], page: 2, size: 20, totalElements: 20, totalPages: 1 })
      .mockResolvedValueOnce(makePage(0, [active], 1))
    createProduct.mockResolvedValue({})
    const user = userEvent.setup()
    renderPage('/app/catalog/products?page=2')
    await screen.findByRole('heading', { name: 'Arena' })
    await user.click(screen.getByRole('button', { name: 'Crear producto' }))
    const form = within(await screen.findByRole('dialog'))
    await user.type(form.getByRole('textbox', { name: 'Nombre' }), 'Cal')
    await user.selectOptions(form.getByRole('combobox', { name: 'Categoría' }), '3')
    await user.type(form.getByRole('textbox', { name: 'Precio de referencia' }), '12')
    await user.selectOptions(form.getByRole('combobox', { name: 'Disponibilidad' }), 'true')
    await user.click(form.getByRole('button', { name: 'Guardar producto' }))
    await waitFor(() => expect(screen.getByTestId('location')).toHaveTextContent('page=0'))
    await waitFor(() => expect(listProducts).toHaveBeenCalledTimes(3))
  })

  it('cancela sin escribir y confirma desactivación y reactivación sin quitar la fila', async () => {
    listProducts.mockResolvedValueOnce(makePage(0, [active]))
      .mockResolvedValueOnce(makePage(0, [{ ...active, activo: false }]))
      .mockResolvedValueOnce(makePage(0, [active]))
    deactivateProduct.mockResolvedValue({})
    reactivateProduct.mockResolvedValue({})
    const user = userEvent.setup()
    renderPage()
    await screen.findByRole('heading', { name: 'Arena' })
    await user.click(screen.getByRole('button', { name: 'Desactivar Arena' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('¿Confirmás la desactivación de Arena?')
    await user.click(screen.getByRole('button', { name: 'Cancelar' }))
    expect(deactivateProduct).not.toHaveBeenCalled()
    await user.click(screen.getByRole('button', { name: 'Desactivar Arena' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar desactivación' }))
    await waitFor(() => expect(deactivateProduct).toHaveBeenCalledTimes(1))
    expect(deactivateProduct).toHaveBeenCalledWith(1)
    expect(await screen.findByRole('button', { name: 'Reactivar Arena' })).toBeInTheDocument()
    expect(screen.getByText(/ID 1 · Categoría 3 · Inactivo/)).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Reactivar Arena' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar reactivación' }))
    await waitFor(() => expect(reactivateProduct).toHaveBeenCalledWith(1))
    expect(await screen.findByRole('button', { name: 'Desactivar Arena' })).toBeInTheDocument()
    expect(listProducts).toHaveBeenCalledTimes(3)
  })

  it('bloquea acciones duplicadas durante la transición y exige lectura exitosa tras 5xx', async () => {
    listProducts.mockResolvedValue(makePage(0, [active]))
    let rejectMutation
    deactivateProduct.mockImplementation(() => new Promise((_, reject) => { rejectMutation = reject }))
    const user = userEvent.setup()
    renderPage()
    await screen.findByRole('heading', { name: 'Arena' })
    await user.click(screen.getByRole('button', { name: 'Desactivar Arena' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar desactivación' }))
    expect(screen.getByRole('button', { name: 'Desactivar Arena' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Crear producto' })).toBeDisabled()
    expect(deactivateProduct).toHaveBeenCalledTimes(1)
    await act(async () => rejectMutation({ status: 503, message: 'Sin respuesta' }))
    expect(await screen.findByText('Sin respuesta')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Desactivar Arena' })).toBeDisabled()
    listProducts.mockRejectedValueOnce(new Error('Lectura fallida'))
    await user.click(screen.getByRole('button', { name: 'Consultar estado actual' }))
    expect(await screen.findByText('Lectura fallida')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Crear producto' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: 'Consultar estado actual' }))
    expect(await screen.findByRole('button', { name: 'Desactivar Arena' })).toBeEnabled()
    expect(deactivateProduct).toHaveBeenCalledTimes(1)
  })

  it('recorre buscar, crear, editar características y cambiar estado en la misma sesión', async () => {
    const created = { ...active, id: 9, nombre: 'Cal' }
    let listed = [active]
    listProducts.mockImplementation(async () => makePage(0, listed, 1))
    createProduct.mockImplementation(async () => { listed = [created]; return created })
    getProduct.mockResolvedValue({ ...created, caracteristicas: [] })
    updateProduct.mockResolvedValue({})
    deactivateProduct.mockImplementation(async () => { listed = [{ ...created, activo: false }]; return {} })
    reactivateProduct.mockImplementation(async () => { listed = [created]; return {} })
    const user = userEvent.setup()
    renderPage()
    await screen.findByRole('heading', { name: 'Arena' })
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), 'Cal')
    await user.click(screen.getByRole('button', { name: 'Buscar' }))
    await waitFor(() => expect(listProducts).toHaveBeenLastCalledWith(0, 'Cal', { signal: expect.any(AbortSignal) }))
    await user.click(screen.getByRole('button', { name: 'Crear producto' }))
    const form = within(await screen.findByRole('dialog'))
    await user.type(form.getByRole('textbox', { name: 'Nombre' }), 'Cal')
    await user.selectOptions(form.getByRole('combobox', { name: 'Categoría' }), '3')
    await user.type(form.getByRole('textbox', { name: 'Precio de referencia' }), '12')
    await user.selectOptions(form.getByRole('combobox', { name: 'Disponibilidad' }), 'true')
    await user.click(form.getByRole('button', { name: 'Guardar producto' }))
    expect(await screen.findByRole('button', { name: 'Editar Cal' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Editar Cal' }))
    const edit = within(await screen.findByRole('dialog'))
    await user.click(edit.getByRole('button', { name: 'Agregar característica' }))
    await user.selectOptions(edit.getByRole('combobox', { name: 'Característica' }), '7')
    await user.type(edit.getByRole('textbox', { name: 'Valor' }), 'Blanco')
    await user.click(edit.getByRole('button', { name: 'Guardar cambios' }))
    await waitFor(() => expect(updateProduct).toHaveBeenCalledWith(9, expect.objectContaining({ caracteristicas: [{ caracteristicaId: 7, valor: 'Blanco', unidad: '' }] })))
    await user.click(await screen.findByRole('button', { name: 'Desactivar Cal' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar desactivación' }))
    await user.click(await screen.findByRole('button', { name: 'Reactivar Cal' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar reactivación' }))
    expect(await screen.findByRole('button', { name: 'Desactivar Cal' })).toBeInTheDocument()
    expect(screen.getByTestId('location')).toHaveTextContent('nombre=Cal&page=0')
  })
})
