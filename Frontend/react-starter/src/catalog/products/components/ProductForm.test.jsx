import { render, screen } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { ProductForm } from './ProductForm.jsx'

const categories = [{ id: 1, nombre: 'Activa', activo: true }, { id: 2, nombre: 'Inactiva', activo: false }]
const characteristics = [{ id: 3, nombre: 'Color' }, { id: 4, nombre: 'Peso' }]

describe('ProductForm', () => {
  it('edita solo datos compartidos y reserva Color para las variantes', async () => {
    const user = userEvent.setup()
    const submit = vi.fn()
    const product = { nombre: 'Pintura', categoriaId: 1, descripcion: 'Interior', precioReferencia: 100, disponible: true,
      variantes: [{ id: 11, caracteristicaId: 3, valor: 'Rojo' }, { id: 12, caracteristicaId: 3, valor: 'Blanco' }],
      caracteristicas: [{ caracteristicaId: 4, valor: '20', unidad: 'L' }] }
    render(<ProductForm categories={categories} characteristics={characteristics} initialValues={product} onSubmit={submit} onCancel={() => {}} />)
    expect(screen.queryByRole('textbox', { name: 'Precio de referencia' })).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    const payload = submit.mock.calls[0][0]
    expect(payload.caracteristicas).toEqual([{ caracteristicaId: 4, valor: '20', unidad: 'L' }])
    expect(payload).not.toHaveProperty('precioReferencia')
    expect(payload).not.toHaveProperty('disponible')
    expect(screen.getByRole('button', { name: 'Agregar característica' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: 'Quitar característica' }))
    await user.click(screen.getByRole('button', { name: 'Agregar característica' }))
    expect(screen.getByRole('combobox', { name: 'Característica' })).not.toHaveTextContent('Color')
  })
  it('permite omitir subcategoría y limpia la selección al cambiar de padre', async () => {
    const user = userEvent.setup()
    const submit = vi.fn()
    render(<ProductForm categories={[...categories, { id: 3, nombre: 'Otra activa', activo: true }]} subcategories={[{ id: 8, categoriaId: 1, nombre: 'Chapas' }]} characteristics={[]} initialValues={{ nombre: 'Arena', categoriaId: 1, subcategoriaId: 8, descripcion: '', precioReferencia: 10, disponible: true }} onSubmit={submit} onCancel={() => {}} />)
    const subcategory = screen.getByRole('combobox', { name: 'Subcategoría' })
    expect(subcategory).toHaveValue('8')
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    expect(submit).toHaveBeenLastCalledWith(expect.objectContaining({ categoriaId: 1, subcategoriaId: 8 }))
    await user.selectOptions(screen.getByRole('combobox', { name: 'Categoría' }), '3')
    expect(subcategory).toHaveValue('')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Categoría' }), '1')
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    expect(submit).toHaveBeenCalledWith(expect.objectContaining({ categoriaId: 1, subcategoriaId: null }))
  })
  it('valida precio positivo, escala, categoría y disponibilidad antes de enviar', async () => {
    const submit = vi.fn()
    const user = userEvent.setup()
    render(<ProductForm categories={categories} characteristics={characteristics} onSubmit={submit} onCancel={() => {}} />)
    expect(screen.getByRole('textbox', { name: 'Nombre' })).toHaveAttribute('maxLength', '160')
    expect(screen.getByRole('textbox', { name: 'Descripción' })).toHaveAttribute('maxLength', '1000')
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), 'Cal')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Categoría' }), '1')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Disponibilidad' }), 'false')
    const price = screen.getByRole('textbox', { name: 'Precio de referencia' })
    await user.type(price, '0')
    await user.click(screen.getByRole('button', { name: 'Guardar producto' }))
    expect(submit).not.toHaveBeenCalled()
    await user.clear(price)
    await user.type(price, '1.234')
    await user.click(screen.getByRole('button', { name: 'Guardar producto' }))
    expect(submit).not.toHaveBeenCalled()
    await user.clear(price)
    await user.type(price, '0.01')
    await user.click(screen.getByRole('button', { name: 'Guardar producto' }))
    expect(submit).toHaveBeenCalledWith(expect.objectContaining({ varianteInicial: { sku: null, precioReferencia: '0.01', disponible: false, caracteristicaId: null, valor: null, unidad: null } }))
    expect(submit.mock.calls[0][0]).not.toHaveProperty('precioReferencia')
    expect(submit.mock.calls[0][0]).not.toHaveProperty('disponible')
  })

  it('evita características duplicadas y exige valor; permite quitarlas todas', async () => {
    const submit = vi.fn()
    const user = userEvent.setup()
    render(<ProductForm categories={categories} characteristics={characteristics} initialValues={{ nombre: 'Arena', categoriaId: 1, descripcion: '', precioReferencia: 10, disponible: true, caracteristicas: [{ caracteristicaId: 3, valor: 'Rojo', unidad: '' }] }} onSubmit={submit} onCancel={() => {}} />)
    await user.click(screen.getByRole('button', { name: 'Agregar característica' }))
    expect(screen.getAllByRole('textbox', { name: 'Valor' })[1]).toHaveAttribute('maxLength', '500')
    expect(screen.getAllByRole('combobox', { name: 'Unidad' })[1]).toHaveValue('none')
    expect(screen.getAllByRole('combobox', { name: 'Característica' })[1]).not.toHaveTextContent('Color')
    await user.selectOptions(screen.getAllByRole('combobox', { name: 'Característica' })[1], '4')
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    expect(submit).not.toHaveBeenCalled()
    await user.type(screen.getAllByRole('textbox', { name: 'Valor' })[1], '25')
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    expect(submit).toHaveBeenCalledWith(expect.objectContaining({ caracteristicas: [{ caracteristicaId: 3, valor: 'Rojo', unidad: null }, { caracteristicaId: 4, valor: '25', unidad: null }] }))
    await user.click(screen.getAllByRole('button', { name: 'Quitar característica' })[1])
    await user.click(screen.getByRole('button', { name: 'Quitar característica' }))
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    expect(submit).toHaveBeenLastCalledWith(expect.objectContaining({ caracteristicas: [] }))
  })

  it('envía Color/Rojo como variante inicial y excluye Color de las características compartidas', async () => {
    const user = userEvent.setup()
    const submit = vi.fn()
    render(<ProductForm categories={categories} characteristics={characteristics} onSubmit={submit} onCancel={() => {}} />)
    expect(screen.getByRole('textbox', { name: 'Identificador de la variante (opcional)' })).toHaveAttribute('maxLength', '160')
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), 'Pintura')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Categoría' }), '1')
    await user.type(screen.getByRole('textbox', { name: 'Precio de referencia' }), '100')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Disponibilidad' }), 'true')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Atributo variable opcional' }), '3')
    await user.type(screen.getByRole('textbox', { name: 'Valor de la variante' }), 'Rojo')
    await user.click(screen.getByRole('button', { name: 'Agregar característica' }))
    expect(screen.getByRole('combobox', { name: 'Característica' })).not.toHaveTextContent('Color')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Característica' }), '4')
    await user.type(screen.getByRole('textbox', { name: 'Valor' }), '20')
    await user.click(screen.getByRole('button', { name: 'Guardar producto' }))
    expect(submit).toHaveBeenCalledWith(expect.objectContaining({
      varianteInicial: { sku: null, precioReferencia: '100', disponible: true, caracteristicaId: 3, valor: 'Rojo', unidad: null },
      caracteristicas: [{ caracteristicaId: 4, valor: '20', unidad: null }],
    }))
  })

  it('conserva y puede cambiar una unidad personalizada al editar una característica', async () => {
    const user = userEvent.setup()
    const submit = vi.fn()
    render(<ProductForm categories={categories} characteristics={characteristics} initialValues={{ nombre: 'Arena', categoriaId: 1, descripcion: '', precioReferencia: 10, disponible: true, caracteristicas: [{ caracteristicaId: 4, valor: '10', unidad: 'bolsa' }] }} onSubmit={submit} onCancel={() => {}} />)
    const unit = screen.getByRole('combobox', { name: 'Unidad' })
    expect(unit).toHaveValue('other')
    expect(screen.getByRole('textbox', { name: 'Otra unidad' })).toHaveValue('bolsa')
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    expect(submit).toHaveBeenLastCalledWith(expect.objectContaining({ caracteristicas: [{ caracteristicaId: 4, valor: '10', unidad: 'bolsa' }] }))
    await user.selectOptions(unit, 'other')
    await user.clear(screen.getByRole('textbox', { name: 'Otra unidad' }))
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    expect(submit).toHaveBeenCalledTimes(1)
    await user.type(screen.getByRole('textbox', { name: 'Otra unidad' }), ' caja ')
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    expect(submit).toHaveBeenLastCalledWith(expect.objectContaining({ caracteristicas: [{ caracteristicaId: 4, valor: '10', unidad: 'caja' }] }))
    await user.selectOptions(unit, 'none')
    await user.click(screen.getByRole('button', { name: 'Guardar cambios' }))
    expect(submit).toHaveBeenLastCalledWith(expect.objectContaining({ caracteristicas: [{ caracteristicaId: 4, valor: '10', unidad: null }] }))
  })

  it('envía la abreviatura elegida en la variante inicial', async () => {
    const user = userEvent.setup()
    const submit = vi.fn()
    render(<ProductForm categories={categories} characteristics={characteristics} onSubmit={submit} onCancel={() => {}} />)
    await user.type(screen.getByRole('textbox', { name: 'Nombre' }), 'Arena')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Categoría' }), '1')
    await user.type(screen.getByRole('textbox', { name: 'Precio de referencia' }), '10')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Disponibilidad' }), 'true')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Atributo variable opcional' }), '4')
    await user.type(screen.getByRole('textbox', { name: 'Valor de la variante' }), '20')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Unidad de la variante' }), 'kg')
    await user.click(screen.getByRole('button', { name: 'Guardar producto' }))
    expect(submit).toHaveBeenCalledWith(expect.objectContaining({ varianteInicial: expect.objectContaining({ caracteristicaId: 4, valor: '20', unidad: 'kg' }) }))
  })
})
